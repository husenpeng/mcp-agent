/**
 * Rename every harness-owned `DSH` / `dsh` identifier to `TOMATO` / `tomato`.
 * This repository is a one-time hard fork that never merges upstream, publishes
 * no npm packages, and keeps no compatibility with the old names
 * ([decision](../docs/tomato/adr/0009-tomato-namespace.md)).
 *
 * Three kinds of text change:
 *
 * 1. The npm scope and the `dsh-` leaf prefix. Every `@deepseek-ai/<name>`
 *    reference becomes `@tomato/<name-without-dsh->`; `@deepseek-ai/dsh` is
 *    `@tomato/cli`, `@deepseek-ai/dsh-brand` is `@tomato/branded`, and
 *    `@deepseek-ai/dsh-root` is `@tomato/harness`. Real third-party packages
 *    under the old scope, `@deepseek-ai/libreoffice-kit*`, stay untouched.
 * 2. Harness-owned runtime identifiers: the `DSH_` environment namespace, the
 *    `Dsh*` / `dsh*` code identifiers, the `dsh` command and home directory,
 *    the `dsh-app://` and `dsh-resource://` schemes, `dsh-v*` release tags, and
 *    the `package.json` `dsh` manifest field.
 * 3. Product prose: `DSH`, `dsh`, and the product name `DeepSeek Harness`.
 *
 * DeepSeek's own identity is not harness-owned and stays: `DEEPSEEK_API_KEY`,
 * `api.deepseek.com`, `deepseek-*` model ids, provider ids, the `deepseek`
 * adapter leaves (`llm-deepseek`), and the upstream repository slug
 * `deepseek-harness` in attribution URLs.
 *
 * Files under `.agents/notes/`, `docs/upgrade-guide/`, and `docs/tomato/adr/`
 * record what was true when they were written and are never rewritten.
 * `scripts/snapshots/` records model payloads and is excluded for the same
 * reason. The mapping files themselves are excluded so a resumed run cannot
 * rewrite its own rules.
 *
 * Usage: `pnpm run rescope-to-tomato [--apply|--check]`. Without a mode it
 * reports what would change. `--check` asserts the post-state: no residue
 * outside the whitelist and a second `--apply` would be a no-op.
 */

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, realpathSync, statSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(import.meta.dirname, '..')

/** Files whose recorded content must remain outside the pass. */
const EXCLUDED_PREFIXES = [
  '.agents/notes/', // records what was true when written
  'docs/upgrade-guide/', // published upgrade history
  'docs/persistence-changes/', // published release records
  'docs/tomato/adr/', // decision records
  'scripts/snapshots/', // recorded model payloads
  // Released-format migrations read old logs: their string literals are the
  // values older builds wrote, not current names.
  'packages/session/session-format-v0-to-v1/',
  'packages/session/session-format-v1-to-v2/',
  'packages/session/session-format-v2-to-v3/',
  'packages/session/session-format-v3-to-v4/',
] as const

const EXCLUDED_FILES = new Set([
  'CLAUDE.md', // symlink to AGENTS.md
  'packages/CLAUDE.md',
  'vendor/CLAUDE.md',
  'pnpm-lock.yaml', // regenerated by pnpm install
  'scripts/dependency-catalog/package-lock.json', // recorded npm evidence
  'docs/dependency-catalog.json', // generated from that recorded evidence
  'scripts/rescope-to-tomato.ts',
  'scripts/rescope-to-tomato.spec.ts',
  'scripts/rescope-vendor.ts', // owns the vendor name mapping, edited by hand
  'scripts/rescope-vendor.spec.ts',
  'docs/rescope.md', // documents the vendor mapping, rewritten by hand
  'docs/rescope.zh.md',
  'docs/tomato/decisions.md', // live decision log, rewritten by hand
  // Persistence protocol constants: recorded digests and historical release
  // tags embed these exact seeds and prefixes.
  'scripts/persistence-schema-model.ts',
  'scripts/persistence-finalization.ts',
  'scripts/persistence-formats.ts',
  'scripts/persistence-releases.ts',
  'scripts/gen-dependency-catalog.ts', // recorded npm evidence names the published package
  'scripts/verify-concrete-terms.ts', // excludes historical release snapshots by their dsh tag
  'scripts/doc-standard.spec.ts', // matches historical and current release document names
  'scripts/doc-typecheck.ts', // owns historical package aliases for frozen docs
])

/** Real third-party packages under the old scope; the guard below never renames them. */
const EXTERNAL_SCOPE_PATTERN = /@deepseek-ai\/libreoffice-kit[A-Za-z0-9._*-]*/g

/** Package leaves whose new name is not a plain `dsh-` strip. */
const LEAF_SPECIAL: Readonly<Record<string, string>> = {
  brand: 'branded',
  root: 'harness',
  'subagent-dsh-sdk': 'subagent-sdk',
}

/** Complete package names that need an inner `dsh` removed too. */
const FULL_NAME_SPECIAL: ReadonlyArray<readonly [string, string]> = [
  ['@deepseek-ai/dsh', '@tomato/cli'],
  ['@deepseek-ai/dsh-subagent-dsh-sdk', '@tomato/subagent-sdk'],
  ['@deepseek-ai/dshx', '@tomato/x'],
]

const EXTENSIONS = [
  '.ts', '.tsx', '.mts', '.cts', '.js', '.mjs', '.cjs', '.json', '.jsonl', '.yml', '.yaml',
  '.md', '.tpl', '.ps1', '.sh', '.py', '.cmd', '.bat', '.html', '.css',
  '.txt', '.toml', '.env', '.example', '.c', '.h', '.snap', '.patch',
] as const

/**
 * Identify files the codemod must not scan.
 * @param file - Repository-relative path with forward slash separators.
 * @returns Whether the file is outside the rewrite.
 */
export function isTomatoExcluded(file: string): boolean {
  if (EXCLUDED_FILES.has(file)) return true
  if (EXCLUDED_PREFIXES.some(prefix => file.startsWith(prefix))) return true
  if (file.endsWith('.i18n.yaml')) return true // blob-hash records
  // Released-format session logs are historical inputs: their source kinds and
  // plugin ids are what older builds wrote. V4 logs are current replay outputs
  // and follow the rename.
  if (/^snapshots\/.+\/session(?:\.\d+)?\.v[0-3]\.jsonl$/.test(file)) return true
  if (/^vendor\/[^/]+\/README\.md$/.test(file)) return true // upstream files kept verbatim
  if (/^vendor\/[^/]+\/LICENSE$/.test(file)) return true
  // Dotfile ignore lists are maintained text.
  if (file === '.gitignore' || file === '.npmignore' || file === '.dockerignore') return false
  // Extensionless sources (Makefile, Dockerfile, launchers) are text.
  const name = file.slice(file.lastIndexOf('/') + 1)
  if (!name.includes('.')) return false
  return !EXTENSIONS.some(extension => file.endsWith(extension))
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/** Package leaves the repository actually declares, longest first. */
function packageLeaves(): { leaf: string; mapped: string }[] {
  const files = execFileSync('git', ['ls-files', '*/package.json'], { cwd: root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 })
    .split('\n')
    .filter(file => file !== '' && !file.includes('node_modules'))
  const leaves = new Map<string, string>()
  for (const file of files) {
    const path = resolve(root, file)
    if (!existsSync(path)) continue
    const { name } = JSON.parse(readFileSync(path, 'utf8')) as { name?: string }
    // The scan must work before and after the rename, so a resumed or checked
    // tree derives the same leaf list from either spelling.
    if (name === undefined) continue
    if (name.startsWith('@deepseek-ai/dsh-')) leaves.set(name.slice('@deepseek-ai/dsh-'.length), LEAF_SPECIAL[name.slice('@deepseek-ai/dsh-'.length)] ?? name.slice('@deepseek-ai/dsh-'.length))
    else if (name.startsWith('@tomato/')) leaves.set(name.slice('@tomato/'.length), name.slice('@tomato/'.length))
  }
  for (const [leaf, mapped] of Object.entries(LEAF_SPECIAL)) leaves.set(leaf, mapped)
  return [...leaves].map(([leaf, mapped]) => ({ leaf, mapped })).sort((left, right) => right.leaf.length - left.leaf.length)
}

const LEAVES = packageLeaves()

/** Longest-first alternation so `dsh-session-format` wins over `dsh-session`. */
const LEAF_PATTERN = new RegExp(`\\bdsh-(${LEAVES.map(({ leaf }) => escapeRegExp(leaf)).join('|')})(?![A-Za-z0-9_:-])`, 'g')
const LEAF_MAP = new Map(LEAVES.map(({ leaf, mapped }) => [leaf, mapped]))

/** Ordered rename layers; `--only` applies a subset when landing the change in steps. */
export type RescopeLayer = 'env' | 'ident' | 'pkg' | 'cli' | 'prose'

export const RESCOPE_LAYERS: readonly RescopeLayer[] = ['env', 'ident', 'pkg', 'cli', 'prose']

/** Skill directory names stay as written: archived Agent Notes link to them. */
const SKILL_NAMES = [
  'archive-agent-notes', 'ci-test-reliability', 'client-ui-ux', 'code-review',
  'create-upgrade-guide', 'doc', 'error-handling', 'find-simplifications',
  'merging-stacked-prs', 'official-plugin-artwork', 'pr-description',
  'pre-push-checks', 'prose-standard', 'responsive-ui', 'session-projection',
  'speed-up-perf', 'translate-docs', 'trim-cot-leakage',
] as const
const SKILL_NAME_PATTERN = new RegExp(`\\bdsh-(?:${SKILL_NAMES.join('|')})\\b`, 'g')

/**
 * Rewrite one line of repository text.
 * @param line - One physical line without its newline.
 * @param only - Layers to apply; defaults to every layer.
 * @returns The renamed line.
 */
export function rescopeLine(line: string, only: ReadonlySet<RescopeLayer> = new Set(RESCOPE_LAYERS)): string {
  if (!/DSH|Dsh|dsh|DeepSeek|@deepseek-ai/.test(line)) return line

  // Protect real third-party packages under the old scope before the blanket rules.
  const guards: string[] = []
  let out = line.replace(EXTERNAL_SCOPE_PATTERN, (match) => {
    guards.push(match)
    return `@@TOMATO_EXTERNAL_${guards.length - 1}@@`
  })
  out = out.replace(SKILL_NAME_PATTERN, (match) => {
    guards.push(match)
    return `@@TOMATO_EXTERNAL_${guards.length - 1}@@`
  })
  // A released session source kind: older logs carry this literal, so the
  // current reader must keep accepting it under its original spelling.
  out = out.replace(/dsh-session-title-llm/g, (match) => {
    guards.push(match)
    return `@@TOMATO_EXTERNAL_${guards.length - 1}@@`
  })
  // Frozen Agent Notes keep their historical file names; links into them must
  // keep resolving.
  out = out.replace(/2026-07-29-dsh-source-launch-tsx-esm/g, (match) => {
    guards.push(match)
    return `@@TOMATO_EXTERNAL_${guards.length - 1}@@`
  })

  if (only.has('pkg')) {
    // Complete package names, longest and most specific first.
    for (const [from, to] of FULL_NAME_SPECIAL) {
      out = out.replace(new RegExp(`${escapeRegExp(from)}(?![A-Za-z0-9_-])`, 'g'), to)
    }
    out = out.replace(/@deepseek-ai\/dsh-brand(?![A-Za-z0-9_-])/g, '@tomato/branded')
    out = out.replace(/@deepseek-ai\/dsh-root(?![A-Za-z0-9_-])/g, '@tomato/harness')
    out = out.replace(/@deepseek-ai\/dsh-/g, '@tomato/')
    // Escaped scope inside a regular-expression literal.
    out = out.split('@deepseek-ai\\/').join('@tomato\\/')
    out = out.replace(/@deepseek-ai(\/|:|(?![A-Za-z0-9_-]))/g, (_match, tail: string) => `@tomato${tail}`)
    // Bare package references in prose: `dsh-agent` names the `@tomato/agent` package.
    out = out.replace(LEAF_PATTERN, (_match, leaf: string) => `@tomato/${LEAF_MAP.get(leaf) ?? leaf}`)
  }

  if (only.has('env')) {
    // Environment namespace and the bare acronym, including the
    // `__DSH_...__` globals and `SCREAMING_CASE` identifiers.
    out = out.replace(/DSH_/g, 'TOMATO_')
    out = out.replace(/_DSH_/g, '_TOMATO_')
    out = out.replace(/_DSH\b/g, '_TOMATO')
    out = out.replace(/isDSH(?=[A-Z])/g, 'isTomato')
    out = out.replace(/DSH\b/g, 'TOMATO')
    out = out.replace(/DSH(?=[A-Z])/g, 'TOMATO')
  }

  if (only.has('ident')) {
    // Code identifiers that contain the old prefix, including mid-word forms
    // such as `bundledDshVersion`.
    out = out.replace(/Dsh(?=[A-Z])/g, 'Tomato')
    out = out.replace(/dsh(?=[A-Z])/g, 'tomato')
  }

  if (only.has('cli')) {
    // The package directory drops the inner `dsh` too.
    out = out.split('subagent-dsh-sdk').join('subagent-sdk')
    // Remaining kebab tokens: release tags, URL schemes, temp-directory prefixes.
    out = out.replace(/\bdsh-/g, 'tomato-')
    // The command, home directory, manifest field, and settings namespace.
    out = out.replace(/dsh\b/g, 'tomato')
  }

  if (only.has('prose')) {
    // Product prose; DeepSeek's own identity stays.
    out = out.split('DeepSeek Harness').join('Tomato Harness')
    out = out.split('DeepSeek 的').join('Tomato 的')
  }

  return out.replace(/@@TOMATO_EXTERNAL_(\d+)@@/g, (_match, index: string) => guards[Number(index)] ?? '')
}

/**
 * Apply the rename to a complete file.
 * @param text - Complete source text.
 * @param only - Layers to apply; defaults to every layer.
 * @returns Rewritten text and the number of changed lines.
 */
export function rescopeTomatoText(
  text: string,
  only: ReadonlySet<RescopeLayer> = new Set(RESCOPE_LAYERS),
): { text: string; lines: number } {
  const original = text.split('\n')
  let changes = 0
  const out = original.map((line) => {
    const next = rescopeLine(line, only)
    if (next !== line) changes += 1
    return next
  })
  return { text: out.join('\n'), lines: changes }
}

function classify(file: string): string {
  if (file.endsWith('package.json')) return 'package.json'
  if (/\.(ts|tsx|js|mjs|cjs|tpl|py|ps1|sh|cmd|bat)$/.test(file)) return 'code'
  if (/\.(yml|yaml)$/.test(file)) return 'YAML'
  if (file.endsWith('.md')) return 'Markdown'
  if (/\.(json|jsonl)$/.test(file)) return 'JSON'
  return 'configuration'
}

function main(): void {
  const args = process.argv.slice(2)
  const mode = args.includes('--apply') ? 'apply' : args.includes('--check') ? 'check' : 'dry'
  const onlyArg = args.find(arg => arg.startsWith('--only='))?.slice('--only='.length)
  const only = new Set<RescopeLayer>(onlyArg === undefined
    ? RESCOPE_LAYERS
    : onlyArg.split(',').map((value) => {
      const layer = value.trim() as RescopeLayer
      if (!RESCOPE_LAYERS.includes(layer)) throw new Error(`unknown rescope layer: ${value}`)
      return layer
    }))
  const files = execFileSync('git', ['ls-files', '-z'], { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
    .split('\0')
    .filter(file => file !== '' && !isTomatoExcluded(file) && existsSync(resolve(root, file)) && statSync(resolve(root, file)).isFile())

  const counts = new Map<string, { files: number; lines: number }>()
  const outstanding: string[] = []

  for (const file of files) {
    const path = resolve(root, file)
    const before = readFileSync(path, 'utf8')
    const { text: after, lines } = rescopeTomatoText(before, only)
    if (after === before) continue
    outstanding.push(file)
    const kind = classify(file)
    const current = counts.get(kind) ?? { files: 0, lines: 0 }
    counts.set(kind, { files: current.files + 1, lines: current.lines + lines })
    if (mode === 'apply') writeFileSync(path, after)
  }

  console.log(`rescope-to-tomato: ${mode} over ${String(files.length)} tracked files${args.includes('--only=') || onlyArg !== undefined ? ` (layers: ${[...only].join(', ')})` : ''}`)
  for (const kind of [...counts.keys()].sort()) {
    const { files: count, lines } = counts.get(kind) ?? { files: 0, lines: 0 }
    console.log(`  ${kind.padEnd(16)} ${String(count).padStart(4)} file(s), ${String(lines)} line(s)`)
  }

  if (mode === 'check' && outstanding.length > 0) {
    for (const file of outstanding) console.error(`rescope-to-tomato: residue: ${file}`)
    console.error(`rescope-to-tomato: ${String(outstanding.length)} file(s) still carry an old name; a second --apply would change them.`)
    process.exitCode = 1
    return
  }
  if (mode === 'check') console.log('rescope-to-tomato: post-state verified — no residue, idempotent.')
  else if (mode === 'apply') console.log('rescope-to-tomato: applied. Run `pnpm install` to relink the workspace, then update the hand-maintained mapping files.')
}

// Importing this module for its exported rewrite must not run the codemod.
if (process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  main()
}
