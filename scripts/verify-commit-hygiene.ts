/**
 * Reject build output and local debugging residue in commits, as `RULE.md` defines.
 *
 * `--cached` checks the staged index entries that a commit adds or changes, for the
 * pre-commit hook; without it the gate checks every tracked file, for the hygiene
 * aggregate. Path rules reject compiler emit beside its TypeScript source under a
 * `src/` directory, dependency and build directories, packed tarballs, build-info
 * files, logs, and the ignored local-debugging names (`*.local.*`, `*.scratch.*`,
 * `scratch/`). Content rules read the index through `git grep --cached` and reject
 * focused tests, `debugger` statements, Python breakpoints, and an uppercase
 * `NOCOMMIT` or `DO NOT COMMIT` comment in code and configuration files. Vendored
 * sources keep upstream code, so content rules skip `vendor/`; this gate's own
 * files spell the patterns and are excluded from content rules.
 */

import { spawnSync } from 'node:child_process'
import { resolve } from 'node:path'

const GATE = 'verify-commit-hygiene'
const root = resolve(import.meta.dirname, '..')

/** One rejected path or line. */
export interface HygieneViolation {
  /** Repository-relative POSIX path. */
  readonly file: string
  /** One-based line for content rules; absent for path rules. */
  readonly line?: number
  /** Rule identifier printed in the report. */
  readonly rule: string
  /** What to do instead. */
  readonly fix: string
}

/** Extensions whose files a TypeScript compiler or bundler emits beside a source. */
const EMIT_SUFFIXES = ['.d.ts.map', '.d.mts.map', '.d.cts.map', '.js.map', '.mjs.map', '.cjs.map', '.d.ts', '.d.mts', '.d.cts', '.js', '.mjs', '.cjs'] as const

/** Source extensions that compile to the emit suffixes above. */
const SOURCE_EXTENSIONS = ['.ts', '.tsx', '.mts', '.cts'] as const

/** Path rules checked against every candidate path, in report order. */
const PATH_RULES: ReadonlyArray<{ readonly rule: string; readonly test: RegExp; readonly fix: string }> = [
  { rule: 'dependency directory', test: /(^|\/)node_modules\//u, fix: 'install dependencies with pnpm; never commit them' },
  { rule: 'build output directory', test: /(^|\/)(lib|dist)\//u, fix: 'build output is produced by pnpm run build:artifacts' },
  { rule: 'packed tarball', test: /\.tgz$/u, fix: 'publish or attach the tarball; keep it out of the tree' },
  { rule: 'TypeScript build info', test: /\.tsbuildinfo$/u, fix: 'build info is regenerated by tsc -b' },
  { rule: 'log file', test: /\.log$|(^|\/)desktop-test-logs\//u, fix: 'logs are local diagnostics; attach an excerpt to the issue or PR instead' },
  { rule: 'local debugging file', test: /(^|\/)scratch\/|\.(local|scratch)\.[^/]+$/u, fix: 'local debugging files stay untracked; move lasting checks into a spec' },
]

/**
 * The TypeScript source an emitted file under `src/` was compiled from, if the index holds one.
 * @param file - repository-relative POSIX path.
 * @param indexed - every path in the index.
 * @returns the sibling source path, or undefined when `file` is not emit beside a source.
 */
export function emitSource(file: string, indexed: ReadonlySet<string>): string | undefined {
  if (!/(^|\/)src\//u.test(file)) return undefined
  const suffix = EMIT_SUFFIXES.find(candidate => file.endsWith(candidate))
  if (suffix === undefined) return undefined
  const stem = file.slice(0, -suffix.length)
  return SOURCE_EXTENSIONS.map(extension => `${stem}${extension}`).find(source => indexed.has(source))
}

/**
 * Apply the path rules.
 * @param candidates - repository-relative POSIX paths to judge.
 * @param indexed - every path in the index, used to find emit siblings.
 * @returns one violation per rejected path, in candidate order.
 */
export function pathViolations(candidates: readonly string[], indexed: ReadonlySet<string>): HygieneViolation[] {
  const violations: HygieneViolation[] = []
  for (const file of candidates) {
    const source = emitSource(file, indexed)
    if (source !== undefined) {
      violations.push({ file, rule: 'build output beside source', fix: `delete it; ${source} is the source and the build writes lib/` })
      continue
    }
    const matched = PATH_RULES.find(entry => entry.test.test(file))
    if (matched !== undefined) violations.push({ file, rule: matched.rule, fix: matched.fix })
  }
  return violations
}

/**
 * Content rules: a POSIX extended regular expression for `git grep -E` and the files it applies to.
 * Patterns spell word boundaries as character classes because POSIX ERE has no `\b`.
 */
export const CONTENT_RULES: ReadonlyArray<{
  readonly rule: string
  readonly pattern: string
  readonly ignoreCase: boolean
  readonly pathspec: readonly string[]
  readonly fix: string
}> = [
  {
    rule: 'focused test',
    pattern: '(^|[^A-Za-z0-9_$.])(describe|it|test|suite|bench)(\\.[A-Za-z]+)*\\.only[[:space:]]*\\(',
    ignoreCase: false,
    pathspec: ['*.ts', '*.tsx', '*.mts', '*.cts', '*.js', '*.jsx', '*.mjs', '*.cjs'],
    fix: 'remove .only so the whole file runs; filter locally with vitest -t',
  },
  {
    rule: 'debugger statement',
    pattern: '^[[:space:]]*debugger[[:space:]]*;?[[:space:]]*(//.*)?$',
    ignoreCase: false,
    pathspec: ['*.ts', '*.tsx', '*.mts', '*.cts', '*.js', '*.jsx', '*.mjs', '*.cjs'],
    fix: 'remove the breakpoint',
  },
  {
    rule: 'Python breakpoint',
    pattern: '^[[:space:]]*(breakpoint\\(\\)|import i?pdb([[:space:]]|;|$)|i?pdb\\.set_trace\\(\\))',
    ignoreCase: false,
    pathspec: ['*.py'],
    fix: 'remove the breakpoint',
  },
  {
    rule: 'nocommit marker',
    pattern: '(//|#|/\\*|\\*)[[:space:]]*(NOCOMMIT|NO-COMMIT|DO NOT COMMIT)([^A-Za-z0-9_]|$)',
    ignoreCase: false,
    pathspec: ['*.ts', '*.tsx', '*.mts', '*.cts', '*.js', '*.jsx', '*.mjs', '*.cjs', '*.py', '*.sh', '*.yml', '*.yaml', '*.css'],
    fix: 'the comment marks local debugging code; delete that code before committing',
  },
]

/** Files that spell the content patterns themselves. */
const SELF = ['scripts/verify-commit-hygiene.ts', 'scripts/verify-commit-hygiene.spec.ts'] as const

/**
 * Run git in the repository and return stdout.
 * @param repositoryRoot - absolute repository root.
 * @param args - git arguments.
 * @param okStatuses - exit statuses that are not failures.
 * @returns stdout text.
 * @throws when git cannot start or exits with another status.
 */
function git(repositoryRoot: string, args: readonly string[], okStatuses: readonly number[] = [0]): string {
  const result = spawnSync('git', args, { cwd: repositoryRoot, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 })
  if (result.error !== undefined) throw result.error
  if (result.status === null || !okStatuses.includes(result.status)) {
    throw new Error(`${GATE}: git ${args.join(' ')} exited with ${String(result.status ?? result.signal)}: ${result.stderr.trim()}`)
  }
  return result.stdout
}

/**
 * Split NUL-terminated git output into paths.
 * @param output - `-z` output.
 * @returns non-empty paths.
 */
function nulSeparated(output: string): string[] {
  return output.split('\0').filter(path => path !== '')
}

/**
 * Apply the content rules to index entries.
 * @param repositoryRoot - absolute repository root.
 * @param limitTo - paths to search; undefined searches every tracked file, an empty list searches nothing.
 * @returns one violation per matching line.
 */
export function contentViolations(repositoryRoot: string, limitTo: readonly string[] | undefined): HygieneViolation[] {
  if (limitTo !== undefined && limitTo.length === 0) return []
  const violations: HygieneViolation[] = []
  const excludes = [':(exclude)vendor/**', ...SELF.map(file => `:(exclude)${file}`)]
  for (const entry of CONTENT_RULES) {
    const includes = limitTo === undefined
      ? entry.pathspec.map(glob => `:(glob)**/${glob}`)
      : limitTo.filter(file => entry.pathspec.some(glob => file.endsWith(glob.slice(1)))).map(file => `:(literal)${file}`)
    if (includes.length === 0) continue
    const flags = ['grep', '--cached', '-n', '-z', '-I', '-E', ...entry.ignoreCase ? ['-i'] : []]
    // git grep exits 1 when nothing matches.
    const output = git(repositoryRoot, [...flags, '-e', entry.pattern, '--', ...includes, ...excludes], [0, 1])
    for (const line of output.split('\n')) {
      if (line === '') continue
      const [file, lineNumber] = line.split('\0')
      if (file === undefined || lineNumber === undefined) continue
      violations.push({ file, line: Number(lineNumber), rule: entry.rule, fix: entry.fix })
    }
  }
  return violations
}

/**
 * Check the staged additions and changes, or every tracked file.
 * @param repositoryRoot - absolute repository root.
 * @param cached - true to check only paths the index adds, copies, modifies, or renames relative to HEAD.
 * @returns every violation: path rules first, then content rules.
 */
export function verifyCommitHygiene(repositoryRoot: string = root, cached = false): HygieneViolation[] {
  const indexed = nulSeparated(git(repositoryRoot, ['ls-files', '-z']))
  const candidates = cached
    ? nulSeparated(git(repositoryRoot, ['diff', '--cached', '--name-only', '--diff-filter=ACMR', '--no-renames', '-z']))
    : indexed
  return [
    ...pathViolations(candidates, new Set(indexed)),
    ...contentViolations(repositoryRoot, cached ? candidates : undefined),
  ]
}

function main(): void {
  const cached = process.argv.includes('--cached')
  const violations = verifyCommitHygiene(root, cached)
  const scope = cached ? 'staged changes' : 'tracked files'
  if (violations.length === 0) {
    console.log(`${GATE}: ${scope} contain no build output or local debugging residue.`)
    return
  }
  console.error(`${GATE}: ${String(violations.length)} violation(s) in ${scope} (see RULE.md):\n`)
  for (const violation of violations) {
    const location = violation.line === undefined ? violation.file : `${violation.file}:${String(violation.line)}`
    console.error(`  ${location} — ${violation.rule}: ${violation.fix}`)
  }
  if (cached) console.error('\nUnstage a file with `git restore --staged <path>`.')
  process.exitCode = 1
}

if (import.meta.filename === resolve(process.argv[1] ?? '')) main()
