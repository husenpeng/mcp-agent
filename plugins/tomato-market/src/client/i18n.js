/** Dictionaries keyed by the locales the shell ships. */
export const DICTIONARIES = { zh, en }

/**
 * Register the dictionaries and bind the translator.
 * @param {object} ctx - browser plugin context.
 * @returns {{ t: (key: string, params?: Record<string, unknown>) => string, language: () => string }} translator and active language.
 */
export function installI18n(ctx) {
  ctx.effect(() => ctx.locale.register(NS, DICTIONARIES), 'tomato-market: dictionaries')
  const t = ctx.locale.bind(NS)
  return { t, language: () => ctx.locale.getLocale().active }
}